// 検索欄の語を、比べやすい形（小文字・コロンなし・空白区切り）にする
export function emojiQueryTerms(query: string): string[] {
  return query
    .toLowerCase()
    .replace(/:/g, " ")
    .split(/\s+/)
    .filter((term) => term !== "");
}

// 1語がどれだけ合うか。名前の完全一致 > 名前の前方一致 > 名前に含む > 言葉の前方一致 > 言葉に含む。合わなければ undefined
function termScore(emoji: Emoji, term: string): number | undefined {
  if (emoji.name === term) return 0;
  if (emoji.name.startsWith(term)) return 1;
  if (emoji.name.includes(term)) return 2;
  if (emoji.keywords.some((keyword) => keyword.startsWith(term))) return 3;
  if (emoji.keywords.some((keyword) => keyword.includes(term))) return 4;
  return undefined;
}

// 検索欄の文字で絵文字を絞る。複数の語はすべて合うものだけ。
// 空なら一覧の順のまま全件。合う度合いが同じなら一覧の順（よく使うものが先）を保つ。
// 一覧では見た目が重ならない（別名は keywords に持つ）ので、見た目での重複除去はしない
export function searchEmoji(
  query: string,
  list: readonly Emoji[] = STANDARD_EMOJI,
): Emoji[] {
  const terms = emojiQueryTerms(query);
  const ranked: { emoji: Emoji; score: number; index: number }[] = [];
  list.forEach((emoji, index) => {
    let total = 0;
    for (const term of terms) {
      const score = termScore(emoji, term);
      if (score === undefined) return;
      total += score;
    }
    ranked.push({ emoji, score: total, index });
  });
  ranked.sort((a, b) => a.score - b.score || a.index - b.index);
  return ranked.map(({ emoji }) => emoji);
}
